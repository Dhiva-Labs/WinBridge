import 'package:path/path.dart' as p;

/// What goes into a generated installer.
class InstallerSpec {
  const InstallerSpec({
    required this.appName,
    required this.version,
    required this.mainExecutable,
    required this.files,
    required this.outputFile,
  });

  /// Shown in the installer UI and used for the Start Menu entry and the
  /// uninstall registry key. Comes from `Project.name`, which is already
  /// guaranteed to be a safe path component.
  final String appName;

  /// Displayed, and written to the uninstall entry. `0.0.0` when the project
  /// does not declare one.
  final String version;

  /// Absolute path to the `.exe` the shortcut points at.
  final String mainExecutable;

  /// Absolute paths to everything the installer ships, main executable
  /// included — DLLs, data files, the lot. Emitted into the script by file
  /// name only; see [generateNsisScript].
  final List<String> files;

  /// File *name* of the installer to produce, not a path: makensis runs with
  /// the script's directory as its working directory and writes there.
  final String outputFile;
}

/// Renders a self-contained NSIS script for [spec].
///
/// Deliberately plain: install to Program Files, a Start Menu shortcut, an
/// Add/Remove Programs entry, and an uninstaller. Anything beyond that is a
/// project's own business, which is what `--script` is for.
///
/// Paths are emitted as bare file names, never absolute ones. makensis runs
/// under Wine with the artifact directory as its working directory, and NSIS
/// uses `/` as its *option* prefix — a Unix absolute path handed to it parses
/// as a flag, and one written into `OutFile` would have to survive Wine's path
/// translation. Staying relative sidesteps both.
///
/// Every value is emitted inside double quotes, and each is either a file name
/// WinBridge computed or a name that already passed `isSafeNameComponent`.
/// NSIS has no shell to escape into, but a stray quote would still break the
/// script, so [escapeNsis] handles the two characters that matter.
String generateNsisScript(InstallerSpec spec) {
  final appName = escapeNsis(spec.appName);
  final version = escapeNsis(spec.version);
  final mainExeName = escapeNsis(p.basename(spec.mainExecutable));

  final installLines = <String>[];
  for (final file in spec.files) {
    // Files are flattened into the install directory: the layout WinBridge
    // produces is flat, and preserving arbitrary nesting would need directory
    // bookkeeping this default script deliberately does not have.
    installLines.add('  File "${escapeNsis(p.basename(file))}"');
  }

  final deleteLines = <String>[
    for (final file in spec.files)
      '  Delete "\$INSTDIR\\${escapeNsis(p.basename(file))}"',
  ];

  return '''
; Generated by winbridge package. Edit a copy and pass it with --script to
; take over: this file is regenerated on every run.
Unicode true

!define APPNAME "$appName"
!define APPVERSION "$version"

Name "\${APPNAME}"
OutFile "${escapeNsis(spec.outputFile)}"
InstallDir "\$PROGRAMFILES64\\\${APPNAME}"
InstallDirRegKey HKLM "Software\\\${APPNAME}" "InstallDir"
RequestExecutionLevel admin
SetCompressor /SOLID lzma

Page directory
Page instfiles
UninstPage uninstConfirm
UninstPage instfiles

Section "Install"
  SetOutPath "\$INSTDIR"
${installLines.join('\n')}

  WriteUninstaller "\$INSTDIR\\uninstall.exe"
  WriteRegStr HKLM "Software\\\${APPNAME}" "InstallDir" "\$INSTDIR"

  ; Add/Remove Programs
  !define UNINSTKEY "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\\${APPNAME}"
  WriteRegStr HKLM "\${UNINSTKEY}" "DisplayName" "\${APPNAME}"
  WriteRegStr HKLM "\${UNINSTKEY}" "DisplayVersion" "\${APPVERSION}"
  WriteRegStr HKLM "\${UNINSTKEY}" "UninstallString" '"\$INSTDIR\\uninstall.exe"'
  WriteRegDWORD HKLM "\${UNINSTKEY}" "NoModify" 1
  WriteRegDWORD HKLM "\${UNINSTKEY}" "NoRepair" 1

  CreateDirectory "\$SMPROGRAMS\\\${APPNAME}"
  CreateShortcut "\$SMPROGRAMS\\\${APPNAME}\\\${APPNAME}.lnk" "\$INSTDIR\\$mainExeName"
SectionEnd

Section "Uninstall"
${deleteLines.join('\n')}
  Delete "\$INSTDIR\\uninstall.exe"
  Delete "\$SMPROGRAMS\\\${APPNAME}\\\${APPNAME}.lnk"
  RMDir "\$SMPROGRAMS\\\${APPNAME}"
  RMDir "\$INSTDIR"
  DeleteRegKey HKLM "\${UNINSTKEY}"
  DeleteRegKey HKLM "Software\\\${APPNAME}"
SectionEnd
''';
}

/// Escapes the characters that would end a quoted NSIS string or start an
/// escape inside one. NSIS uses `$\"` for a literal quote and `$$` for a
/// literal dollar.
String escapeNsis(String value) =>
    value.replaceAll(r'$', r'$$').replaceAll('"', r'$\"');
